#!/usr/bin/env python3
"""Generate SKY130 mixed-signal R-2R DAC interfaces for 24-bit state codes.

The resistor ladder accepts offset-binary codes. The digital controller must
convert signed Q7.16 state into an offset code for its declared, rail-safe
state range before restoring it. The ladder's 24-bit topology is an ideal-R
functional model; it does not imply 24-bit physical linearity or ENOB.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "asic/analog/sky130_ms_r2r24.spice"
R = 1_000.0
R2 = 2_000.0


def main() -> None:
    bits = " ".join(f"b{i}" for i in range(23, -1, -1))
    wbits = " ".join(f"w{i}" for i in range(22, -1, -1))
    lines: list[str] = [
        "* Autogenerated by scripts/build_sky130_ms_r2r24.py — do not hand-edit.",
        "* Digital formats (docs/project_spec.yaml quantization.active_formats):",
        "*   weights/membrane/base_threshold: signed_int24_Q7_16",
        "*   beta: unsigned_int24_UQ1_23 (leak phase elsewhere)",
        "* Ideal 1k/2k R provisional pending PDK resistor layout/extraction.",
        "* Large DAC-only switches and low ladder impedance reduce modeled R-2R loading.",
        "* R-2R input is unsigned offset-binary u24; V(out) ~= vlo + (u24/2**24)*(vhi-vlo).",
        "* Do not connect raw two's-complement Q7.16 bits here: map/saturate in the",
        "* digital restore controller for each declared state range and voltage scale.",
        "* Ideal-R schematic only. No resistor matching, switch-Ron, noise, ADC,",
        "* or 24-bit ENOB claim. Digital membrane state remains signed Q7.16.",
        "",
        ".subckt r2r_inv a y vdd vss",
        "Xpd y a vdd vdd sky130_fd_pr__pfet_01v8 w=2 l=0.15 m=50",
        "Xnd y a vss vss sky130_fd_pr__nfet_01v8 w=1 l=0.15 m=50",
        ".ends r2r_inv",
        ".subckt r2r_switch a b en enb vdd vss",
        "Xn a en b vss sky130_fd_pr__nfet_01v8 w=1 l=0.15 m=100",
        "Xp a enb b vdd sky130_fd_pr__pfet_01v8 w=2 l=0.15 m=100",
        ".ends r2r_switch",
        "",
        ".subckt r2r_dac_u24 out",
        f"+ {bits}",
        "+ vhi vlo vdd vss",
    ]
    for i in range(24):
        lines.append(f"Xiv{i} b{i} bb{i} vdd vss r2r_inv")
    lines.append(f"Rterm n0 vlo {R2:.0f}")
    lines.append(f"Rq23 out n22 {R:.0f}")
    for k in range(22, 0, -1):
        lines.append(f"Rq{k} n{k} n{k - 1} {R:.0f}")
    for k in range(23, -1, -1):
        node = "out" if k == 23 else f"n{k}"
        lines.append(f"R2b{k} {node} m{k} {R2:.0f}")
        lines.append(f"Xth{k} vhi m{k} b{k} bb{k} vdd vss r2r_switch")
        lines.append(f"Xtl{k} vlo m{k} bb{k} b{k} vdd vss r2r_switch")
    lines += [
        ".ends r2r_dac_u24",
        "",
        ".subckt membrane_code_vdac_offset_u24 out",
        f"+ {bits}",
        "+ vhi vlo vdd vss",
        f"Xdac out {bits} vhi vlo vdd vss r2r_dac_u24",
        ".ends membrane_code_vdac_offset_u24",
        "",
        ".subckt membrane_restore_write_offset_u24 state vdac",
        f"+ {bits}",
        "+ restore restore_b",
        "+ vhi vlo vdd vss",
        f"Xdac vdac {bits} vhi vlo vdd vss membrane_code_vdac_offset_u24",
        "Xwr vdac state restore restore_b vdd vss transmission_gate",
        ".ends membrane_restore_write_offset_u24",
        "",
        "* |weight| unsigned u23 aligned to the top 23 R-2R bits; b0=0.",
        ".subckt weight_mag_vdac_u23 vw",
        f"+ {wbits}",
        "+ vhi vlo vdd vss",
        "Vb0_tie b0 0 0",
        f"Xdac vw {wbits} b0 vhi vlo vdd vss r2r_dac_u24",
        ".ends weight_mag_vdac_u23",
        "",
        ".subckt and2 a b y vdd vss",
        "Xnand a b yb vdd vss nand2",
        "Xinv yb y vdd vss inv",
        ".ends and2",
        ".subckt nand2 a b y vdd vss",
        "Xp1 y a vdd vdd sky130_fd_pr__pfet_01v8 w=2 l=0.15",
        "Xp2 y b vdd vdd sky130_fd_pr__pfet_01v8 w=2 l=0.15",
        "Xn1 y a n vss sky130_fd_pr__nfet_01v8 w=1 l=0.15",
        "Xn2 n b vss vss sky130_fd_pr__nfet_01v8 w=1 l=0.15",
        ".ends nand2",
        "",
        "* One magnitude DAC; sign selects normal/complement bits at high-impedance switch controls.",
        ".subckt weight_gate_vdac_u23 vw",
        f"+ {wbits}",
        "+ sign_n vhi vlo vdd vss",
        "Xsign_inv sign_n sign_p vdd vss inv",
    ]
    for i in range(23):
        lines += [
            f"Xwg_inv{i} w{i} wn{i} vdd vss inv",
            f"Xwg_pos{i} wn{i} b{i+1} sign_p sign_n vdd vss transmission_gate",
            f"Xwg_neg{i} w{i} b{i+1} sign_n sign_p vdd vss transmission_gate",
        ]
    lines += [
        # For positive weights b23..b1 are complemented and b0=1 (PMOS gate falls).
        # For negative weights b23..b1 are normal and b0=0 (NMOS gate rises).
        f"Xdac vw {' '.join(f'b{i}' for i in range(23,0,-1))} sign_p vhi vlo vdd vss r2r_dac_u24",
        ".ends weight_gate_vdac_u23",
        "",
        "* PMOS current source is fixed at vdd; NMOS current sink is fixed at vss.",
        "* Separate sign-qualified pulse switches connect only the selected path.",
        "* w22..w0 are calibrated unsigned gate codes, not raw signed Q7.16 bits.",
        "* The source Q7.16 weight must remain in digital storage; TT calibration is provisional.",
        "* pulse_pos is active-LOW (PMOS); pulse_neg is active-HIGH (NMOS).",
        ".subckt weight_inject_q716 membrane",
        "+ pulse_pos pulse_neg sign_n",
        f"+ {wbits}",
        "+ vhi vlo ibias_n_off vdd vss",
        "Xwg vw",
        f"+ {wbits} sign_n vhi vlo vdd vss weight_gate_vdac_u23",
        "* P-current source width was tuned from the bounded integrated TT transfer screen.",
        "Xp_bias psrc vw vdd vdd sky130_fd_pr__pfet_01v8 w=11.3 l=2",
        "Xn_bias nsrc vw vss vss sky130_fd_pr__nfet_01v8 w=2 l=2",
        "Xpos_inv pulse_pos pos_req vdd vss inv",
        "Xpos_and pos_req sign_p pos_en vdd vss and2",
        "Xsign_inv sign_n sign_p vdd vss inv",
        "Xneg_and pulse_neg sign_n neg_en vdd vss and2",
        "Xpos_en_inv pos_en pos_enb vdd vss inv",
        "Xneg_en_inv neg_en neg_enb vdd vss inv",
        "Xpos_gate psrc membrane pos_en pos_enb vdd vss transmission_gate",
        "Xneg_gate nsrc membrane neg_en neg_enb vdd vss transmission_gate",
        ".ends weight_inject_q716",
        "",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
