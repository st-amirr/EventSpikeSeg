def test_asic_rtl(
    top: str,
    sources: list[str],
    test_module: str,
    parameters: dict[str, int],
    tmp_path: Path,
) -> None:
    runner = get_runner("icarus")
    runner.build(
        verilog_sources=[ROOT / item for item in sources],
        hdl_toplevel=top,
        build_dir=tmp_path / top,
        always=True,
        build_args=["-g2012"],
        parameters=parameters,
    )
    runner.test(
        hdl_toplevel=top,
        test_module=test_module,
        test_dir=tmp_path / top,
    )
